"""
Data Processing Module
=======================
Handles loading and processing of historical price data for parameter
estimation. Calculates daily logarithmic returns and annualized
historical volatility.

Historical Volatility Estimation:
    1. Compute daily log returns:
           r_t = ln(S_t / S_{t-1})
    
    2. Compute daily standard deviation:
           σ_daily = std(r_t)
    
    3. Annualize:
           σ_annual = σ_daily × √252
    
    where 252 is the typical number of trading days per year.

Important Distinction:
    - Historical data: Real market prices loaded from CSV.
    - Estimated parameters: Volatility and initial price derived from
      historical data.
    - Simulated prices: Future price paths generated by GBM — these are
      NOT real market prices and should not be interpreted as predictions.

Authors: Sayan Goswami, Sovan Pal, Tanmoy Paul
"""

import numpy as np
import pandas as pd
from io import StringIO, BytesIO


def load_price_data(uploaded_file_or_path) -> pd.DataFrame:
    """
    Load historical price data from a CSV file or Streamlit uploaded file.

    Handles common column name variations:
        Date columns: 'Date', 'date', 'DATE', 'Timestamp'
        Price columns: 'Close', 'close', 'CLOSE', 'Close Price',
                       'Adj Close', 'Closing Price', 'LTP'

    Parameters
    ----------
    uploaded_file_or_path : str or file-like
        Path to CSV file, or a Streamlit UploadedFile object.

    Returns
    -------
    pd.DataFrame
        DataFrame with 'Date' and 'Close' columns, sorted by date,
        with clean numeric values and no missing data.

    Raises
    ------
    ValueError
        If required columns cannot be identified.
    """
    # Read the CSV
    if isinstance(uploaded_file_or_path, str):
        # File path string
        df = pd.read_csv(uploaded_file_or_path, comment='#')
    else:
        # Streamlit UploadedFile or file-like object
        df = pd.read_csv(uploaded_file_or_path, comment='#')

    # --- Identify Date column ---
    date_candidates = ['Date', 'date', 'DATE', 'Timestamp', 'timestamp',
                       'Trade Date', 'TIMESTAMP']
    date_col = None
    for col in date_candidates:
        if col in df.columns:
            date_col = col
            break

    if date_col is None:
        # Try the first column if it looks like dates
        first_col = df.columns[0]
        try:
            pd.to_datetime(df[first_col].head())
            date_col = first_col
        except (ValueError, TypeError):
            raise ValueError(
                f"Could not identify a date column. Available columns: {list(df.columns)}")

    # --- Identify Close price column ---
    close_candidates = ['Close', 'close', 'CLOSE', 'Close Price',
                        'Adj Close', 'Closing Price', 'LTP', 'ltp',
                        'Last Traded Price', 'Adj_Close']
    close_col = None
    for col in close_candidates:
        if col in df.columns:
            close_col = col
            break

    if close_col is None:
        # Try to find any column with 'close' in the name
        for col in df.columns:
            if 'close' in col.lower():
                close_col = col
                break

    if close_col is None:
        raise ValueError(
            f"Could not identify a close price column. Available columns: {list(df.columns)}")

    # --- Build clean DataFrame ---
    result = pd.DataFrame()
    result['Date'] = pd.to_datetime(df[date_col])
    # Clean numeric values: remove commas and convert
    result['Close'] = pd.to_numeric(
        df[close_col].astype(str).str.replace(',', ''), errors='coerce')

    # Remove rows with missing values
    result = result.dropna().reset_index(drop=True)

    # Sort by date (ascending)
    result = result.sort_values('Date').reset_index(drop=True)

    return result


def calculate_log_returns(prices: pd.Series) -> pd.Series:
    """
    Calculate daily logarithmic returns.

    Formula: r_t = ln(S_t / S_{t-1}) = ln(S_t) - ln(S_{t-1})

    Log returns are preferred over simple returns because:
    1. They are additive over time: total return = sum of daily log returns
    2. They are approximately normally distributed (for GBM)
    3. They can range from -∞ to +∞ (no lower bound issue)

    Parameters
    ----------
    prices : pd.Series
        Series of closing prices.

    Returns
    -------
    pd.Series
        Series of daily log returns (first value is NaN, dropped).
    """
    log_returns = np.log(prices / prices.shift(1))
    return log_returns.dropna()


def calculate_historical_volatility(returns: pd.Series,
                                     trading_days: int = 252) -> float:
    """
    Calculate annualized historical volatility from daily log returns.

    Formula:
        σ_daily = std(r_t)                  (standard deviation of daily returns)
        σ_annual = σ_daily × √(trading_days) (annualized volatility)

    Parameters
    ----------
    returns : pd.Series
        Series of daily log returns.
    trading_days : int
        Number of trading days per year (default: 252 for most markets).

    Returns
    -------
    float
        Annualized historical volatility.
    """
    daily_vol = returns.std()
    annualized_vol = daily_vol * np.sqrt(trading_days)
    return float(annualized_vol)


def estimate_parameters(df: pd.DataFrame) -> dict:
    """
    Extract model parameters from historical price data.

    This function processes a DataFrame (output of load_price_data) and
    estimates the key parameters needed for Monte Carlo simulation.

    Parameters
    ----------
    df : pd.DataFrame
        DataFrame with 'Date' and 'Close' columns.

    Returns
    -------
    dict
        'S0'             : Last closing price (initial price for simulation).
        'sigma'          : Annualized historical volatility.
        'daily_returns'  : pd.Series of daily log returns.
        'annualized_vol' : Same as sigma (alias for clarity).
        'mean_return'    : Annualized mean log return.
        'n_observations' : Number of data points used.
    """
    prices = df['Close']
    daily_returns = calculate_log_returns(prices)
    annualized_vol = calculate_historical_volatility(daily_returns)

    # Mean annualized return
    mean_daily_return = daily_returns.mean()
    mean_annualized = mean_daily_return * 252

    return {
        'S0': float(prices.iloc[-1]),
        'sigma': annualized_vol,
        'daily_returns': daily_returns,
        'annualized_vol': annualized_vol,
        'mean_return': float(mean_annualized),
        'n_observations': len(prices)
    }


def create_sample_data(S0: float = 22000.0, mu: float = 0.12,
                       sigma: float = 0.18, n_days: int = 252,
                       seed: int = 42) -> pd.DataFrame:
    """
    Create sample SYNTHETIC price data for testing purposes.

    IMPORTANT: This generates ARTIFICIAL data using GBM simulation.
    It is NOT real market data and should not be used for actual
    trading decisions. Use real data from NSE or Yahoo Finance for
    meaningful analysis.

    Parameters
    ----------
    S0 : float
        Starting price (default: 22000, roughly NIFTY 50 level).
    mu : float
        Drift parameter (real-world, not risk-neutral).
    sigma : float
        Volatility.
    n_days : int
        Number of trading days.
    seed : int
        Random seed.

    Returns
    -------
    pd.DataFrame
        DataFrame with 'Date' and 'Close' columns.
    """
    rng = np.random.RandomState(seed)
    dt = 1 / 252

    # Generate daily log returns
    Z = rng.standard_normal(n_days)
    log_returns = (mu - 0.5 * sigma ** 2) * dt + sigma * np.sqrt(dt) * Z

    # Build price path
    prices = S0 * np.exp(np.cumsum(log_returns))
    prices = np.insert(prices, 0, S0)

    # Generate business dates
    dates = pd.bdate_range(start='2025-11-03', periods=n_days + 1)

    df = pd.DataFrame({
        'Date': dates,
        'Close': np.round(prices, 2)
    })

    return df
